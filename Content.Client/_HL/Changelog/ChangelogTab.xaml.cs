using System.Linq;
using System.Numerics;
using Content.Client.Resources;
using Content.Client.Stylesheets;
using Robust.Client.AutoGenerated;
using Robust.Client.ResourceManagement;
using Robust.Client.UserInterface;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;
using static Robust.Client.UserInterface.Controls.BoxContainer;

namespace Content.Client._HL.Changelog;

/// <summary>
/// A single UI tab inside the changelog window that displays the contents of a specific changelog file.
/// It takes care of ordering the versions, pinning the unread versions at the top, and drawing that fancy "New Changes" divider.
/// </summary>
[GenerateTypedNameReferences]
public sealed partial class ChangelogTab : Control
{
    [Dependency] private readonly IResourceCache _resourceCache = null!;

    public ChangelogTab()
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);
    }

    public void PopulateChangelog(ChangelogManager.Changelog changelog)
    {
        var hasRead = !changelog.HasUnreadEntries;

        var byVersion = changelog.Entries
            .Select(kvp =>
            {
                var isRead = !changelog.UnreadEntries.Contains(kvp.Key);
                return (Version: kvp.Key, Entry: kvp.Value, IsRead: isRead);
            })
            .OrderBy(x => x.IsRead) 
            .ThenByDescending(x => x.Version);

        var first = true;

        foreach (var data in byVersion)
        {
            if (!first)
            {
                ChangelogBody.AddChild(new Control { Margin = new Thickness(4) });
            }

            if (data.IsRead && !hasRead)
            {
                hasRead = true;

                var upArrow = _resourceCache.GetTexture("/Textures/Interface/Changelog/up_arrow.svg.192dpi.png");
                var readDivider = new BoxContainer { Orientation = LayoutOrientation.Vertical };

                var hBox = new BoxContainer
                {
                    Orientation = LayoutOrientation.Horizontal,
                    HorizontalAlignment = HAlignment.Center,
                    Children =
                    {
                        new TextureRect
                        {
                            Texture = upArrow,
                            ModulateSelfOverride = Color.FromHex("#888"),
                            TextureScale = new Vector2(0.5f, 0.5f),
                            Margin = new Thickness(4, 3),
                            VerticalAlignment = VAlignment.Bottom
                        },
                        new Label
                        {
                            Align = Label.AlignMode.Center,
                            Text = Loc.GetString("changelog-new-changes"),
                            FontColorOverride = Color.FromHex("#888"),
                        },
                        new TextureRect
                        {
                            Texture = upArrow,
                            ModulateSelfOverride = Color.FromHex("#888"),
                            TextureScale = new Vector2(0.5f, 0.5f),
                            Margin = new Thickness(4, 3),
                            VerticalAlignment = VAlignment.Bottom
                        }
                    }
                };

                readDivider.AddChild(hBox);
                readDivider.AddChild(new PanelContainer { StyleClasses = { StyleClass.LowDivider } });
                ChangelogBody.AddChild(readDivider);

                if (first)
                    readDivider.SetPositionInParent(ChangelogBody.ChildCount - 2);
            }

            first = false;

            ChangelogBody.AddChild(new ChangelogVersion(data.Version, data.Entry, _resourceCache));
        }
    }
}

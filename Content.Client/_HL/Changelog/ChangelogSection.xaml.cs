using Content.Client.Resources;
using Robust.Client.AutoGenerated;
using Robust.Client.ResourceManagement;
using Robust.Client.UserInterface;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Utility;
using static Content.Client._HL.Changelog.ChangelogManager;

namespace Content.Client._HL.Changelog;

/// <summary>
/// A UI control representing a specific category of changes (like "Bug Fixes" or "Tweaks").
/// Sets up the correct colored icon and title based on the category type, then spawns the individual entries underneath it.
/// </summary>
[GenerateTypedNameReferences]
public sealed partial class ChangelogSection : Control
{
    public ChangelogSection(ChangelogLineType type, List<ChangelogChange> changes, IResourceCache cache)
    {
        RobustXamlLoader.Load(this);

        var (file, color, title) = type switch
        {
            ChangelogLineType.Add => ("plus.svg.192dpi.png", "#6ED18D", "Additions"),
            ChangelogLineType.Remove => ("minus.svg.192dpi.png", "#D16E6E", "Removals"),
            ChangelogLineType.Fix => ("bug.svg.192dpi.png", "#D1BA6E", "Bug Fixes"),
            ChangelogLineType.Tweak => ("wrench.svg.192dpi.png", "#6E96D1", "Tweaks"),
            _ => throw new ArgumentOutOfRangeException(nameof(type), type, null)
        };

        Icon.Texture = cache.GetTexture(new ResPath($"/Textures/Interface/Changelog/{file}"));
        Icon.ModulateSelfOverride = Color.FromHex(color);
        
        SectionTitle.Text = title;
        SectionTitle.FontColorOverride = Color.FromHex(color);

        foreach (var change in changes)
        {
            EntriesContainer.AddChild(new ChangelogEntry(change));
        }
    }
}
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Utility;
using static Content.Client._HL.Changelog.ChangelogManager;

namespace Content.Client._HL.Changelog;

/// <summary>
/// This is the UI control for a single changelog line item.
/// It renders the actual message, and the author and commit buttons so you can click them to open the respective URLs.
/// You'll see these stacked inside a <see cref="ChangelogSection"/>.
/// </summary>
[GenerateTypedNameReferences]
public sealed partial class ChangelogEntry : Control
{
    [Dependency] private readonly IUriOpener _uriOpener = null!;

    public ChangelogEntry(ChangelogChange change)
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);

        var msg = new FormattedMessage();
        
        // Bullet
        msg.PushColor(Color.FromHex("#aaaaaa"));
        msg.AddText("• ");
        msg.Pop();
        
        // Message
        msg.AddText(change.Message);
        EntryLabel.SetMessage(msg);

        // Author Button
        AuthorButton.Text = $"Author: {change.Author}";
        AuthorButton.OnPressed += _ => _uriOpener.OpenUri($"https://code.hardlight.space/{Uri.EscapeDataString(change.Author)}");

        // Commit Hash Button (if it exists)
        if (string.IsNullOrWhiteSpace(change.Hash)) return;
        CommitButton.Visible = true;
        CommitButton.Text = "Commit";
        CommitButton.OnPressed += _ => _uriOpener.OpenUri($"https://code.hardlight.space/HardLight/HardLight/commit/{Uri.EscapeDataString(change.Hash)}");
    }
}
using Robust.Client.AutoGenerated;
using Robust.Client.ResourceManagement;
using Robust.Client.UserInterface;
using Robust.Client.UserInterface.XAML;
using static Content.Client._HL.Changelog.ChangelogManager;

namespace Content.Client._HL.Changelog;

[GenerateTypedNameReferences]
public sealed partial class ChangelogVersion : Control
{
    public ChangelogVersion(Version version, ChangelogManager.ChangelogEntry entry, IResourceCache cache)
    {
        RobustXamlLoader.Load(this);
        VersionLabel.Text = version.ToString();

        var sections = new (ChangelogLineType Type, List<ChangelogChange>? Changes)[]
        {
            (ChangelogLineType.Add, entry.Add),
            (ChangelogLineType.Fix, entry.Fix),
            (ChangelogLineType.Tweak, entry.Tweak),
            (ChangelogLineType.Remove, entry.Remove)
        };
        foreach (var (type, changes) in sections)
        {
            if (changes is { Count: > 0 })
                SectionsContainer.AddChild(new ChangelogSection(type, changes, cache));
        }
    }
}